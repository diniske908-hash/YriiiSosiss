"""Ответы клиентам: сначала быстрые правила, потом нейросеть с жёстким таймаутом.

Правила дают мгновенный ответ на частые вопросы (цены, сроки, что входит).
Для остального — нейросеть, но не дольше 12 секунд: бот не должен зависать.
"""
from __future__ import annotations

import sys
from concurrent.futures import ThreadPoolExecutor, TimeoutError as FutureTimeout
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

from llm import chat  # noqa: E402

PRICE_SHORT = "Бот записи — 10 000 ₽, запуск 5–10 дней. Оплата 50/50. Могу показать демо."
CUSTOM_SHORT = ("Индивидуальный дизайн — от 15 000 ₽, свой домен — +3 000 ₽, "
                "связка с CRM — от 10 000 ₽. Точную сумму согласует владелец.")

EXTRAS = ("Сайт с записью — 20 000 ₽, напоминания +5 000 ₽, поддержка 2 000 ₽/мес, "
          "свой дизайн от 15 000 ₽, домен +3 000 ₽, CRM от 10 000 ₽.")

RULES: list[tuple[tuple[str, ...], str]] = [
    (("сколько", "цена", "стоит", "стоимость", "прайс"), PRICE_SHORT),
    (("дизайн", "логотип", "фирменн"), CUSTOM_SHORT),
    (("crm", "1с", "1c", "интеграц"), "Связка с CRM или 1С — от 10 000 ₽, точную сумму согласует владелец."),
    (("филиал", "две клиник", "второй клиник"), "Второй филиал в одном боте — от 5 000 ₽."),
    (("оплат", "эквайринг", "картой"), "Онлайн-оплата при записи — от 8 000 ₽."),
    (("срок", "когда будет", "как быстро", "долго"), "Запуск 5–10 дней с момента, как пришлёте услуги и прайс."),
    (("доплат", "добавить", "сайт", "домен", "поддержк"), EXTRAS),
    (("что входит", "что получу", "как работает"), "Запись, заявка администратору, перенос, отмена с причиной, маршрут до клиники."),
    (("демо", "пример", "посмотреть", "показать"), "Вот как это выглядит: https://ufa-zapis.surge.sh/demos/moj-doktor.html"),
    (("max", "макс", "телеграм", "telegram"), "Работает и в MAX, и в Telegram — как вам удобнее."),
    (("компьютер", "пк", "ноутбук", "принтер", "сеть", "вирус"), "Компьютерная помощь тоже есть: ремонт и чистка ПК, принтеры, сеть."),
]

KNOWLEDGE = """Ты — помощник сервиса «Зиныч IT» (Уфа). Делаем бота записи для клиник.

Факты:
- Бот записи — 10 000 ₽, запуск 5–10 дней.
- Бот вместе с сайтом — 20 000 ₽.
- Напоминания клиентам — +5 000 ₽.
- Поддержка — 2 000 ₽/мес.
- Оплата 50% в начале, 50% после запуска. Правки 14 дней бесплатно.
- Работает в MAX и Telegram: клиент выбирает услугу, день и время, заявка приходит администратору.
- Демо: https://ufa-zapis.surge.sh/demos/moj-doktor.html
Нестандарт (цены «от», точную согласует владелец):
- индивидуальный дизайн — от 15 000 ₽; свой домен — +3 000 ₽; CRM/1С — от 10 000 ₽;
  второй филиал — от 5 000 ₽; онлайн-оплата — от 8 000 ₽; нестандартная задача — от 20 000 ₽.

Правила: 2–4 строки, простой русский, без канцелярита. Не выдумывай цены и сроки.
Если вопрос про конкретную клинику, договор, скидки или нестандартную задачу не из списка —
ответь ровно «НУЖЕН_ЧЕЛОВЕК» и больше ничего."""


COMPLAINT_MARKERS = (
    "не работает", "не открывается", "не нажимается", "не приходит", "сломал",
    "ошибк", "глючит", "кнопк", "непонятно", "не понятно", "не так", "неудобно",
)


def rule_answer(text: str) -> str | None:
    low = text.lower()
    for keys, reply in RULES:
        if any(k in low for k in keys):
            return reply
    return None


def _ask_llm(question: str) -> str:
    return chat([
        {"role": "system", "content": KNOWLEDGE},
        {"role": "user", "content": question[:500]},
    ], max_tokens=300, temperature=0.3, retries=1)


def answer(question: str) -> str | None:
    """Быстрый ответ или None, если нужен человек. Никогда не висит дольше 12 секунд."""
    low = question.lower()
    if any(m in low for m in COMPLAINT_MARKERS):
        return None          # жалобы разбирает человек, а не бот

    quick = rule_answer(question)
    if quick:
        return quick

    try:
        with ThreadPoolExecutor(max_workers=1) as pool:
            text = pool.submit(_ask_llm, question).result(timeout=12).strip()
    except (FutureTimeout, Exception):  # noqa: BLE001
        return None

    if not text or "НУЖЕН_ЧЕЛОВЕК" in text.upper() or len(text) < 10:
        return None
    return text[:900]
